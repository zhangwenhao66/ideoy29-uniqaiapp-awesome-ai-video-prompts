#!/usr/bin/env python3
"""Generate the Markdown views of data/prompts/ and the generated sections of README.md.

Usage:
  python3 scripts/build.py            # writes prompts/by-model/*.md, prompts/by-use-case/*.md, README sections
  python3 scripts/build.py --check    # exit 1 if any generated file is out of date (CI and tests run this)

README.md keeps hand-written text outside two marker pairs:
  <!-- generated:stats:start --> ... <!-- generated:stats:end -->
  <!-- generated:list:start -->  ... <!-- generated:list:end -->
Everything between the markers is replaced by this script, so the list and the numbers in the
README can never drift from the JSON. Edit data/prompts/*.json, run this, commit both.
Translations (README.ru.md, README.zh-CN.md, ...) get the same two blocks with the labels from
scripts/readme_i18n.py; the hand-written text around the markers is never touched.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _lib import MODE_LABEL, ROOT, load_meta, load_records, model_name, slug_anchor, use_case_name  # noqa: E402
from readme_i18n import lang_of, strings, use_case_label  # noqa: E402
from stats import compute, markdown as stats_markdown  # noqa: E402

OUT_DIR = os.path.join(ROOT, "prompts")
README = os.path.join(ROOT, "README.md")


def readme_files():
    """README.md first, then every README.<lang>.md, as (path, lang)."""
    out = []
    for n in sorted(os.listdir(ROOT)):
        lang = lang_of(n)
        if lang and os.path.isfile(os.path.join(ROOT, n)):
            out.append((os.path.join(ROOT, n), lang))
    return sorted(out, key=lambda x: (x[1] != "en", x[0]))


def entry_md(r, meta, level=4):
    h = "#" * level
    meta_line = []
    meta_line.append("Model: " + ", ".join("`%s`" % m for m in r["models"]))
    meta_line.append("Mode: `%s`" % r["mode"])
    if "duration_s" in r:
        meta_line.append("Duration: %d s" % r["duration_s"])
    meta_line.append("Aspect: %s" % r["aspect"])
    meta_line.append("Rendered: " + ("yes" if r.get("rendered_on") else "no report yet"))
    lines = ["%s %s" % (h, r["title"]), ""]
    lines.append(" · ".join(meta_line))
    lines.append("")
    lines.append("```text")
    lines.append(r["prompt"])
    lines.append("```")
    lines.append("")
    lines.append("**Why it works.** " + r["why"])
    for rep in r.get("rendered_on", []):
        lines.append("")
        lines.append("**Rendered on %s (%s).** %s" % (model_name(meta, rep["model"]), rep["date"], rep["result"]))
    if r.get("guide"):
        g = r["guide"]
        lines.append("")
        lines.append("Follows: [%s](%s), checked %s." % (g["label"], g["url"], g["date"]))
    lines.append("")
    lines.append("<sub>id `%s` · tags: %s</sub>" % (r["id"], ", ".join("`%s`" % t for t in r["tags"])))
    lines.append("")
    return "\n".join(lines)


def page(title, intro, groups, meta, back):
    """groups: list of (heading, [records])."""
    out = ["# " + title, "", intro, "", back, ""]
    out.append("Contents: " + " · ".join("[%s](#%s)" % (h, slug_anchor(h)) for h, _ in groups))
    out.append("")
    for heading, recs in groups:
        out.append("## " + heading)
        out.append("")
        for r in recs:
            out.append(entry_md(r, meta))
    out.append("---")
    out.append("")
    out.append("Prompts are CC BY 4.0, attribution \"UniqAI, https://github.com/uniqaiapp/awesome-ai-video-prompts\". Generated by `scripts/build.py`; edit `data/prompts/*.json`, not this file.")
    out.append("")
    return "\n".join(out)


def build_pages(records, meta):
    files = {}
    back = "[Back to the README](../../README.md) · [By model](../by-model/) · [By use case](../by-use-case/)"
    for mkey, m in meta["models"].items():
        recs = [r for r in records if mkey in r["models"]]
        if not recs:
            continue
        groups = []
        for uc in meta["use_cases"]:
            sub = [r for r in recs if r["use_case"] == uc]
            if sub:
                groups.append((use_case_name(meta, uc), sub))
        intro = "%d prompts written for %s (%s), grouped by use case. \"Rendered\" means somebody filed a report with what came out; see the README for what that does and does not mean." % (len(recs), m["name"], m["vendor"])
        files[os.path.join("by-model", mkey + ".md")] = page(m["name"] + " prompts", intro, groups, meta, back)
    for uc, name in meta["use_cases"].items():
        recs = [r for r in records if r["use_case"] == uc]
        if not recs:
            continue
        groups = []
        for mkey in meta["models"]:
            sub = [r for r in recs if r["models"][0] == mkey]
            if sub:
                groups.append(("Written first for " + model_name(meta, mkey), sub))
        intro = "%d prompts for %s, grouped by the model each one was written for first (other models it suits are listed on the entry)." % (len(recs), name.lower())
        files[os.path.join("by-use-case", uc + ".md")] = page(name + " prompts", intro, groups, meta, back)
    return files


def readme_list(records, meta, lang="en"):
    """The compact awesome-list section embedded in README: per use case, one line per prompt.
    Titles, model keys and link targets stay English in every language; labels come from readme_i18n."""
    t = strings(lang)
    out = []
    for uc in meta["use_cases"]:
        recs = [r for r in records if r["use_case"] == uc]
        if not recs:
            continue
        name = use_case_label(meta, lang, uc)
        out.append("### %s" % name)
        out.append("")
        for r in recs:
            dur = (" · %d s" % r["duration_s"]) if "duration_s" in r else ""
            mark = (" · " + t["rendered"]) if r.get("rendered_on") else ""
            out.append("- [%s](prompts/by-use-case/%s.md#%s) · %s · `%s`%s%s" % (
                r["title"], uc, slug_anchor(r["title"]), ", ".join(r["models"]), r["mode"], dur, mark))
        out.append("")
        out.append("[%s](prompts/by-use-case/%s.md)" % (t["all_link"](name), uc))
        out.append("")
    out.append("### %s" % t["by_model"])
    out.append("")
    for mkey, m in meta["models"].items():
        n = sum(1 for r in records if mkey in r["models"])
        if n:
            kind = t["audio"] if m.get("audio") else (t["image_model"] if m["kind"] == "image" else t["silent"])
            out.append("- [%s](prompts/by-model/%s.md) · %s · %s" % (m["name"], mkey, t["count"](n), kind))
    out.append("")
    return "\n".join(out)


def replace_between(text, start, end, body):
    i = text.index(start) + len(start)
    j = text.index(end)
    return text[:i] + "\n" + body.strip("\n") + "\n" + text[j:]


def render_all():
    meta = load_meta()
    records = load_records()
    files = build_pages(records, meta)
    stats = compute(records, meta)
    readmes = {}
    for path, lang in readme_files():
        with open(path, encoding="utf-8") as f:
            txt = f.read()
        txt = replace_between(txt, "<!-- generated:stats:start -->", "<!-- generated:stats:end -->", stats_markdown(stats, meta, lang))
        txt = replace_between(txt, "<!-- generated:list:start -->", "<!-- generated:list:end -->", readme_list(records, meta, lang))
        readmes[path] = txt
    return files, readmes


def main(argv):
    if "--help" in argv or "-h" in argv:
        print(__doc__.strip())
        return 0
    check = "--check" in argv
    files, readmes = render_all()
    stale = []
    for rel, content in files.items():
        path = os.path.join(OUT_DIR, rel)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != content:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
    for path, readme in readmes.items():
        old = open(path, encoding="utf-8").read()
        if old != readme:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(readme)
    # remove generated pages whose source vanished
    for sub in ("by-model", "by-use-case"):
        d = os.path.join(OUT_DIR, sub)
        if os.path.isdir(d):
            for n in os.listdir(d):
                rel = os.path.join(sub, n)
                if n.endswith(".md") and rel not in files:
                    stale.append(os.path.relpath(os.path.join(d, n), ROOT))
                    if not check:
                        os.remove(os.path.join(d, n))
    if check:
        if stale:
            print("out of date (run python3 scripts/build.py): " + ", ".join(stale))
            return 1
        print("ok: generated files are up to date (%d pages + sections in %d README file(s))" % (len(files), len(readmes)))
        return 0
    print("wrote %d pages under prompts/ and refreshed %s (%d file(s) changed)" % (len(files), ", ".join(os.path.basename(p) for p in readmes), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
